def make_entities(prefix, rows, fields):
    items = []
    index = {}
    for i, row in enumerate(rows, start=1):
        item_id = f"{prefix}{i:03d}"
        item = {"id": item_id}
        for field, value in zip(fields, row):
            item[field] = value
        items.append(item)
        index[row[0]] = item_id
    return items, index


