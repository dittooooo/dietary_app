# 把標準化後的 request payload 轉成安全的 Neo4j read-only Cypher。
class TemplateTextToCypherTranslator:
    # 根據料理配對結果與慢性病資料產生檢索 Cypher，並做安全檢查。
    def translate(self, payload: Dict[str, Any]) -> Dict[str, str]:
        cypher = build_graph_retrieval_cypher(
            payload.get("dish_match_results", []),
            resolve_diseases_from_payload(payload),
        )
        validate_nutrition_return_schema(cypher)
        return {
            "cypher": cypher,
            "question_type": payload.get("question_type") or "single_dish",
            "rationale": "Generated by template translator from dish match scores, fallback strategies, and chronic diseases.",
            "cypher_mode": "template",
        }


