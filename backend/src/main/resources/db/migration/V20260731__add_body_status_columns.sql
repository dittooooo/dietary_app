ALTER TABLE user_profile
    ADD COLUMN IF NOT EXISTS bmr DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS tdee DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS recommended_calories DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS body_score INTEGER NOT NULL DEFAULT 50,
    ADD COLUMN IF NOT EXISTS muscle_score INTEGER NOT NULL DEFAULT 50,
    ADD COLUMN IF NOT EXISTS body_type VARCHAR(255) NOT NULL DEFAULT 'NORMAL',
    ADD COLUMN IF NOT EXISTS last_settle_date DATE;

UPDATE user_profile
SET body_type = 'NORMAL'
WHERE body_type IS NULL
   OR body_type = ''
   OR UPPER(body_type) = 'STANDARD';
