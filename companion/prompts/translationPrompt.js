   - 若為「飲品 + 額外加料」，請拆分為飲品與配料（如「水玉/寒天」翻譯為「寒天蒟蒻」；「墨玉/仙草」翻譯為「仙草凍」；「波霸/珍珠」翻譯為「粉圓」或「珍珠」）。
